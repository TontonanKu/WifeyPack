function t(key) {
  const lang = AppState.currentLang || 'id';
  if (i18n[lang] && i18n[lang][key]) {
    return i18n[lang][key];
  }
  return i18n['id'][key] || key;
}

function setLanguage(lang, triggerRender = true) {
  if (!['id', 'en', 'zh', 'ko'].includes(lang)) lang = 'id';
  AppState.currentLang = lang;
  localStorage.setItem('wifey_lang', lang);

  // Update top language buttons styling
  ['id', 'en', 'zh', 'ko'].forEach(l => {
    const topBtn = document.getElementById(`top-lang-${l}`);
    if (topBtn) {
      topBtn.className = l === lang
        ? 'px-2 py-0.5 rounded-full bg-magenta text-white transition-all text-[11px] font-black shadow-brutal-sm'
        : 'px-2 py-0.5 rounded-full text-neutral-700 hover:text-magenta transition-all text-[11px] font-bold';
    }

    const footerBtn = document.getElementById(`lang-btn-${l}`);
    if (footerBtn) {
      footerBtn.className = l === lang
        ? 'flex-1 px-3 py-1.5 rounded-xl text-xs font-black bg-magenta text-white brutal-border shadow-brutal-sm transition-all flex items-center justify-center gap-1.5 cursor-pointer'
        : 'flex-1 px-3 py-1.5 rounded-xl text-xs font-bold text-neutral-700 hover:text-magenta transition-all flex items-center justify-center gap-1.5 cursor-pointer';
    }
  });

  applyTranslations();

  if (triggerRender) {
    if (!AppState.currentAccountId) {
      renderAccountsDirectory();
    } else {
      renderProfileUI();
      renderPosts();
    }
    const langNames = { id: 'Indonesia', en: 'English', zh: '中文', ko: '한국어' };
    showToast(`🌐 Bahasa: ${langNames[lang] || lang}`);
  }
}

